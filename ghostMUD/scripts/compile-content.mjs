import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = path.join(root, 'src', 'narrative', 'content');
const outputPath = path.join(root, 'src', 'narrative', 'generated', 'authored_registry.js');

async function listFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(absolute));
    else files.push(absolute);
  }
  return files;
}

function payloadEntries(payload) {
  if (Array.isArray(payload)) return payload;
  if (Array.isArray(payload?.entries)) return payload.entries;
  return payload && typeof payload === 'object' ? [payload] : [];
}

function addUnique(target, seen, entry, source) {
  if (!entry?.id) throw new Error('[ContentCompile] entry without id in ' + source);
  if (seen.has(entry.id)) throw new Error('[ContentCompile] duplicate id: ' + entry.id);
  seen.add(entry.id);
  target.push({ revision: 1, ...entry, source: entry.source || source });
}

async function main() {
  const narrativeEntries = [];
  const assetEntries = [];
  const narrativeIds = new Set();
  const assetIds = new Set();
  const files = await listFiles(contentDir);

  for (const absolute of files.sort()) {
    const relative = path.relative(root, absolute).replace(/\\/g, '/');
    if (!relative.endsWith('.narrative.json') && !relative.endsWith('.assets.json')) continue;
    const payload = JSON.parse(await fs.readFile(absolute, 'utf8'));
    const target = relative.endsWith('.assets.json') ? assetEntries : narrativeEntries;
    const seen = relative.endsWith('.assets.json') ? assetIds : narrativeIds;
    payloadEntries(payload).forEach(entry => addUnique(target, seen, entry, relative));
  }

  const moduleText = '// Generated by scripts/compile-content.mjs. Do not edit.\n'
    + 'export const AUTHORED_NARRATIVE_ENTRIES = Object.freeze(' + JSON.stringify(narrativeEntries, null, 2) + ');\n'
    + 'export const AUTHORED_ASSET_ENTRIES = Object.freeze(' + JSON.stringify(assetEntries, null, 2) + ');\n';
  await fs.writeFile(outputPath, moduleText, 'utf8');
  console.log('[ContentCompile] narrative=' + narrativeEntries.length + ', assets=' + assetEntries.length);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});